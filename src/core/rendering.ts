/** Turns structured data into Markdown. Stable ordering and no timestamps, for clean git diffs (FR-OUT-018). */
import { REASONS } from "./constants/discovery.js";
import { DOCUMENT_FILES, SPECS_FOLDER_NAME, SPEC_FILES } from "./constants/paths.js";
import { GUIDELINE_BASELINE, GUIDELINE_SECTIONS, type GuidelineSection } from "./guidelines-baseline.js";
import type { ScanResult } from "./ports.js";
import type { GeneratedSpec, OpenQuestion, ProjectData } from "./schemas.js";

/** Keeps text from the project or Claude from breaking a table (FR-OUT-019). */
export function escapeCell(text: string): string {
  return text.replaceAll("\\", "\\\\").replaceAll("|", "\\|").replace(/\r?\n/g, "<br>");
}

function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const header = `| ${headers.join(" | ")} |`;
  const divider = `|${headers.map(() => "---").join("|")}|`;
  const body = rows.map((row) => `| ${row.map(escapeCell).join(" | ")} |`);
  return [header, divider, ...body].join("\n");
}

function bullets(items: readonly string[], empty: string): string {
  return items.length === 0 ? empty : items.map((item) => `- ${item}`).join("\n");
}

function evidenceText(evidence: readonly string[]): string {
  return evidence.map((item) => `\`${item}\``).join(", ");
}

function document(...parts: readonly string[]): string {
  return `${parts.join("\n\n")}\n`;
}

function renderReadme(project: ProjectData, specs: readonly GeneratedSpec[]): string {
  const rows = specs.map((spec) => [`[${spec.name}](specs/${spec.name}/spec.md)`, spec.goal, `\`${spec.area}\``]);
  return document(
    "# SDD documentation",
    project.overview.purpose,
    "Generated by cclinic from this project's code and documents. Treat these files as the source of truth for what the project must do, and keep them updated as it changes.",
    "## Reading order",
    `1. [overview.md](overview.md)
2. [stack.md](stack.md)
3. [architecture.md](architecture.md)
4. [developer-guidelines.md](developer-guidelines.md)
5. [open-questions.md](open-questions.md)
6. The specs below`,
    "## Specs",
    table(["Spec", "Goal", "Area code"], rows),
    "## The three files in each spec",
    table(
      ["File", "Question it answers", "Written for", "ID format"],
      [
        ["`spec.md`", "What must the software do?", "Developers and AI coding tools", "`FR-<AREA>-NNN`"],
        ["`validation.md`", "Does it meet the need?", "Product owners and reviewers", "`VAL-<AREA>-NNN`"],
        ["`verification.md`", "Which test proves each requirement?", "Automation testers", "`TC-<AREA>-NNN`"],
      ],
    ),
    "## Requirement status",
    table(
      ["Status", "Meaning"],
      [
        ["`confirmed`", "Code and documents agree"],
        ["`code-only`", "Found in code, with no supporting documents"],
        ["`docs-only`", "Found in documents only. It may not be built yet"],
      ],
    ),
    "## Rules",
    `- AI coding tools follow [developer-guidelines.md](developer-guidelines.md) for all code.
- Automation testers write tests from each spec's \`verification.md\`.
- Don't assume a \`docs-only\` requirement is implemented.
- Check [open-questions.md](open-questions.md) before relying on a disputed requirement.
- If the project has cclinic's skills (\`create-spec\`, \`refine-spec\`, \`write-code\`, \`implement-spec\`, \`test-spec\`), use them for that work.`,
  );
}

function renderOverview(project: ProjectData): string {
  const { overview } = project;
  return document(
    "# Overview",
    "## Purpose",
    overview.purpose,
    "## Users",
    bullets(overview.users, "Not found in the project."),
    "## Scope",
    bullets(overview.scope, "Not found in the project."),
    "## Non-goals",
    bullets(overview.nonGoals, "None found in the project."),
    "## Glossary",
    overview.glossary.length === 0
      ? "None found in the project."
      : table(
          ["Term", "Meaning"],
          overview.glossary.map((entry) => [entry.term, entry.meaning]),
        ),
  );
}

const STACK_CATEGORIES = ["Language", "Framework", "Database", "Test tool", "Build tool", "CI tool"] as const;

function renderStack(project: ProjectData): string {
  const found = project.stack.map((item) => item.category.toLowerCase());
  const missing = STACK_CATEGORIES.filter(
    (category) => !found.some((value) => value.includes(category.split(" ")[0]?.toLowerCase() ?? category)),
  );
  return document(
    "# Technology stack",
    project.stack.length === 0
      ? "No technologies were found."
      : table(
          ["Category", "Name", "Version", "Evidence"],
          project.stack.map((item) => [item.category, item.name, item.version, evidenceText(item.evidence)]),
        ),
    ...(missing.length === 0 ? [] : [`**Not found in the project:** ${missing.join(", ")}.`]),
  );
}

function renderArchitecture(project: ProjectData): string {
  const { architecture } = project;
  return document(
    "# Architecture",
    "## Main parts",
    architecture.parts.length === 0
      ? "No distinct parts were found."
      : table(
          ["Part", "Responsibility", "Depends on", "Evidence"],
          architecture.parts.map((part) => [
            part.name,
            part.responsibility,
            part.dependsOn.join(", "),
            evidenceText(part.evidence),
          ]),
        ),
    "## Data flow",
    bullets(architecture.dataFlow, "Not found in the project."),
    "## External systems",
    bullets(architecture.externalSystems, "None found."),
    "## Structural problems",
    bullets(
      architecture.problems.map((item) => `${item.problem} ${evidenceText(item.evidence)}`.trim()),
      "None found.",
    ),
  );
}

function renderGuidelines(project: ProjectData): string {
  const knownSections: ReadonlySet<string> = new Set(GUIDELINE_SECTIONS);
  const sectionFor = (section: string): GuidelineSection =>
    knownSections.has(section) ? (section as GuidelineSection) : "Language rules";

  const parts: string[] = ["# Developer guidelines"];
  for (const section of GUIDELINE_SECTIONS) {
    parts.push(`## ${section}`, GUIDELINE_BASELINE[section]);
    const items = project.guidelines.filter((item) => sectionFor(item.section) === section);
    if (items.length > 0) {
      parts.push(
        "### For this project",
        items
          .map((item) => {
            const label = item.label === "observed" ? "Observed" : "Recommended";
            const evidence = item.evidence.length === 0 ? "" : ` (${evidenceText(item.evidence)})`;
            return `- **${label}:** ${item.guidance}${evidence}`;
          })
          .join("\n"),
      );
    } else if (section === "Language rules" && project.stack.length === 0) {
      parts.push("No language was detected, so stack-specific guidance wasn't possible.");
    }
  }
  return document(...parts);
}

function renderOpenQuestions(questions: readonly OpenQuestion[]): string {
  return document(
    "# Open questions",
    questions.length === 0
      ? "There are no open questions."
      : table(
          ["Question", "Evidence"],
          questions.map((item) => [item.question, evidenceText(item.evidence)]),
        ),
  );
}

export interface ScanReportData {
  readonly scan: ScanResult;
  readonly warnings: readonly string[];
  readonly redactions: ReadonlyMap<string, number>;
}

export function renderScanReport({ scan, warnings, redactions }: ScanReportData): string {
  const byKind = (kind: string): number => scan.included.filter((file) => file.kind === kind).length;
  // Tool folders such as .cclinic appear only after the first run, which would change the report between identical runs.
  const skipped = scan.skipped.filter((entry) => entry.reason !== REASONS.tool);
  return document(
    "# Scan report",
    "## Totals",
    table(
      ["Item", "Count"],
      [
        ["Included: code", String(byKind("code"))],
        ["Included: config", String(byKind("config"))],
        ["Included: documents", String(byKind("document"))],
        ["Skipped files and folders", String(skipped.length)],
      ],
    ),
    "## Warnings",
    bullets(warnings, "None."),
    "## Redactions",
    redactions.size === 0
      ? "None."
      : table(
          ["File", "Secrets removed"],
          [...redactions.entries()]
            .sort(([left], [right]) => left.localeCompare(right))
            .map(([path, count]) => [path, String(count)]),
        ),
    "## Skipped",
    skipped.length === 0
      ? "None."
      : table(
          ["Path", "Reason"],
          skipped.map((entry) => [entry.path, entry.reason]),
        ),
  );
}

function renderSpec(spec: GeneratedSpec): string {
  return document(
    `# ${spec.name}`,
    "## Goal",
    spec.goal,
    "## Requirements",
    table(
      ["ID", "Requirement", "Status", "Evidence"],
      spec.requirements.map((item) => [item.id, item.statement, item.status, evidenceText(item.evidence)]),
    ),
    "## Edge cases",
    bullets(spec.edgeCases, "None known."),
    "## Non-goals",
    bullets(spec.nonGoals, "None known."),
  );
}

function renderValidation(spec: GeneratedSpec): string {
  return document(
    `# ${spec.name}: validation`,
    "Acceptance criteria from the user's point of view.",
    table(
      ["ID", "Covers", "User need", "Accepted when"],
      spec.acceptanceCriteria.map((item) => [item.id, item.covers.join(", "), item.userNeed, item.acceptedWhen]),
    ),
  );
}

function renderVerification(spec: GeneratedSpec): string {
  return document(
    `# ${spec.name}: verification`,
    "Test cases for automation testers. Start each automated test's name with its `TC` ID.",
    "## Test setup",
    bullets(spec.testSetup, "No test setup was found in the project. See [open questions](../../open-questions.md)."),
    "## Test cases",
    table(
      ["ID", "Covers", "Level", "Given", "When", "Then"],
      spec.testCases.map((item) => [item.id, item.covers.join(", "), item.level, item.given, item.when, item.then]),
    ),
  );
}

export function renderDocuments(
  project: ProjectData,
  unsortedSpecs: readonly GeneratedSpec[],
  scanReport: ScanReportData,
): Map<string, string> {
  const specs = [...unsortedSpecs].sort((left, right) => left.name.localeCompare(right.name));
  const seenQuestions = new Set<string>();
  const questions = [...project.openQuestions, ...specs.flatMap((spec) => spec.openQuestions)].filter((item) => {
    const normalized = item.question.trim().toLowerCase();
    if (seenQuestions.has(normalized)) return false;
    seenQuestions.add(normalized);
    return true;
  });
  const files = new Map<string, string>([
    [DOCUMENT_FILES.README, renderReadme(project, specs)],
    [DOCUMENT_FILES.OVERVIEW, renderOverview(project)],
    [DOCUMENT_FILES.STACK, renderStack(project)],
    [DOCUMENT_FILES.ARCHITECTURE, renderArchitecture(project)],
    [DOCUMENT_FILES.GUIDELINES, renderGuidelines(project)],
    [DOCUMENT_FILES.OPEN_QUESTIONS, renderOpenQuestions(questions)],
    [DOCUMENT_FILES.SCAN_REPORT, renderScanReport(scanReport)],
  ]);
  for (const spec of specs) {
    files.set(`${SPECS_FOLDER_NAME}/${spec.name}/${SPEC_FILES.SPEC}`, renderSpec(spec));
    files.set(`${SPECS_FOLDER_NAME}/${spec.name}/${SPEC_FILES.VALIDATION}`, renderValidation(spec));
    files.set(`${SPECS_FOLDER_NAME}/${spec.name}/${SPEC_FILES.VERIFICATION}`, renderVerification(spec));
  }
  return files;
}
